import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

export const TOKEN_LIMIT = 5000;
export const BYTES_PER_TOKEN = 4;

// Maximum allowed size is 20,000 bytes (5,000 tokens * 4 bytes/token)
export const MAX_BYTES = TOKEN_LIMIT * BYTES_PER_TOKEN;

const LOCKFILE_PATTERNS = [
  /(?:^|[/\\])(?:pnpm-lock\.yaml|package-lock\.json|yarn\.lock|bun\.lockb?|skills-lock\.json|composer\.lock|cargo\.lock|gemfile\.lock|poetry\.lock|flake\.lock|go\.sum)$/iu,
  /\.lock$/iu,
  /-lock\.(?:yaml|yml|json)$/iu,
  /(?:^|[/\\])npm-shrinkwrap\.json$/iu,
];

const CODEGEN_FILE_PATTERNS = [
  /\.(?:gen|generated)\.[a-z0-9]+$/iu,
  /(?:^|[/\\])routeTree\.gen\.ts$/iu,
  /\.pb\.(?:go|ts|js)$/iu,
  /_pb2\.py$/iu,
  /\.min\.(?:js|css)$/iu,
  /\.map$/iu,
];

const IGNORED_DIR_PATTERNS = [
  /(?:^|[/\\])(?:node_modules|\.git|\.vite-hooks\/_|dist|dist-ssr|build|\.output|\.tanstack|\.alchemy|coverage|vendor)(?:[/\\]|$)/iu,
];

const BINARY_AND_MEDIA_EXTENSIONS = [
  /\.(?:png|jpe?g|gif|webp|ico|svg|avif|bmp|tiff)$/iu,
  /\.(?:woff|woff2|ttf|eot|otf)$/iu,
  /\.(?:mp4|webm|mp3|wav|ogg|flac|aac|mov)$/iu,
  /\.(?:zip|tar|gz|tgz|7z|rar|exe|bin|wasm|dylib|so|dll|iso|dmg)$/iu,
  /\.(?:pdf|docx?|xlsx?|pptx?)$/iu,
];

const CODEGEN_CONTENT_MARKERS = [
  /@generated\b/iu,
  /generated by\b/iu,
  /auto-generated\b/iu,
  /automatically generated\b/iu,
  /this file (?:was|is) generated\b/iu,
  /\bcode generated by\b/iu,
  /\bdo not edit\b/iu,
  /\bchanges will be overwritten\b/iu,
  /\bwill be lost if the code is regenerated\b/iu,
  /\bvendored from\b/iu,
];

export interface FileViolation {
  filePath: string;
  bytes: number;
  tokens: number;
}

export interface CheckResult {
  violations: FileViolation[];
  checkedFiles: string[];
  ignoredFiles: string[];
}

/** Calculate tokens from byte length using tokens = bytes / 4 */
export const calculateTokens = (bytes: number): number =>
  Math.ceil(bytes / BYTES_PER_TOKEN);

/** Check if a file should be ignored (not authored by agents, e.g. lockfiles, codegen, vendor, binaries) */
export const isIgnoredFile = (
  filePath: string,
  contentSnippet?: string
): boolean => {
  const normalizedPath = filePath.replaceAll("\\", "/");

  for (const pattern of IGNORED_DIR_PATTERNS) {
    if (pattern.test(normalizedPath)) {
      return true;
    }
  }

  for (const pattern of LOCKFILE_PATTERNS) {
    if (pattern.test(normalizedPath)) {
      return true;
    }
  }

  for (const pattern of CODEGEN_FILE_PATTERNS) {
    if (pattern.test(normalizedPath)) {
      return true;
    }
  }

  for (const pattern of BINARY_AND_MEDIA_EXTENSIONS) {
    if (pattern.test(normalizedPath)) {
      return true;
    }
  }

  if (contentSnippet !== undefined && contentSnippet.length > 0) {
    if (contentSnippet.includes("\0")) {
      return true;
    }

    for (const marker of CODEGEN_CONTENT_MARKERS) {
      if (marker.test(contentSnippet)) {
        return true;
      }
    }
  }

  return false;
};

/** Retrieve the size in bytes of a staged file */
export const getStagedFileSize = (
  filePath: string,
  repoRoot = process.cwd()
): number | null => {
  const normalizedPath = path.isAbsolute(filePath)
    ? path.relative(repoRoot, filePath).replaceAll("\\", "/")
    : filePath.replaceAll("\\", "/");

  try {
    const stdout = execFileSync(
      "git",
      ["cat-file", "-s", `:${normalizedPath}`],
      {
        cwd: repoRoot,
        encoding: "utf-8",
        stdio: ["pipe", "pipe", "pipe"],
      }
    ).trim();

    const size = Math.trunc(Number(stdout));

    if (!Number.isNaN(size)) {
      return size;
    }
  } catch {
    // If not in git index (e.g. unstaged or deleted or outside repo), fallback to filesystem
  }

  const absolutePath = path.isAbsolute(filePath)
    ? filePath
    : path.resolve(repoRoot, filePath);

  if (fs.existsSync(absolutePath)) {
    try {
      const stat = fs.statSync(absolutePath);

      if (stat.isFile()) {
        return stat.size;
      }
    } catch {
      return null;
    }
  }

  return null;
};

/** Read the first chunk of a staged file for content marker inspection */
export const getStagedFileSnippet = (
  filePath: string,
  repoRoot = process.cwd(),
  maxBytes = 4096
): string => {
  const absolutePath = path.isAbsolute(filePath)
    ? filePath
    : path.resolve(repoRoot, filePath);

  if (fs.existsSync(absolutePath)) {
    try {
      const fd = fs.openSync(absolutePath, "r");
      const buffer = Buffer.alloc(maxBytes);
      const bytesRead = fs.readSync(fd, buffer, 0, maxBytes, 0);
      fs.closeSync(fd);

      return buffer.toString("utf-8", 0, bytesRead);
    } catch {
      // Fall through to git cat-file
    }
  }

  const normalizedPath = path.isAbsolute(filePath)
    ? path.relative(repoRoot, filePath).replaceAll("\\", "/")
    : filePath.replaceAll("\\", "/");

  try {
    const result = spawnSync("git", ["cat-file", "-p", `:${normalizedPath}`], {
      cwd: repoRoot,
      maxBuffer: 64 * 1024,
    });

    if (result.stdout.length > 0) {
      return result.stdout.toString("utf-8", 0, maxBytes);
    }
  } catch {
    return "";
  }

  return "";
};

/** Get list of currently staged files in git */
export const getStagedFilesFromGit = (repoRoot = process.cwd()): string[] => {
  try {
    const stdout = execFileSync(
      "git",
      ["diff", "--cached", "--name-only", "--diff-filter=ACMR"],
      {
        cwd: repoRoot,
        encoding: "utf-8",
        stdio: ["pipe", "pipe", "pipe"],
      }
    );

    const files: string[] = [];

    for (const line of stdout.split("\n")) {
      const trimmed = line.trim();

      if (trimmed.length > 0) {
        files.push(trimmed);
      }
    }

    return files;
  } catch {
    return [];
  }
};

/** Check files for the 5,000 token limit */
export const checkFiles = (
  files: readonly string[],
  repoRoot = process.cwd()
): CheckResult => {
  const violations: FileViolation[] = [];
  const checkedFiles: string[] = [];
  const ignoredFiles: string[] = [];

  for (const file of files) {
    if (isIgnoredFile(file)) {
      ignoredFiles.push(file);
      continue;
    }

    const size = getStagedFileSize(file, repoRoot);

    if (size === null) {
      // Deleted file or inaccessible
      continue;
    }

    const snippet = getStagedFileSnippet(file, repoRoot);

    if (isIgnoredFile(file, snippet)) {
      ignoredFiles.push(file);
      continue;
    }

    checkedFiles.push(file);
    const tokens = calculateTokens(size);

    if (tokens > TOKEN_LIMIT) {
      violations.push({
        bytes: size,
        filePath: file,
        tokens,
      });
    }
  }

  return { checkedFiles, ignoredFiles, violations };
};

/** Format actionable error message with explicit file splitting guidance */
export const formatErrorMessage = (
  violations: readonly FileViolation[],
  repoRoot = process.cwd()
): string => {
  const count = violations.length;
  const fileWord = count === 1 ? "file" : "files";
  const verbWord = count === 1 ? "exceeds" : "exceed";

  const lines: string[] = [
    "",
    "=".repeat(80),
    `COMMIT REJECTED: ${count} staged ${fileWord} ${verbWord} the 5,000 token limit.`,
    "=".repeat(80),
    "",
    "Token count rule: Tokens = bytes / 4 (Max limit: 5,000 tokens = 20,000 bytes).",
    "Only agent-authored files are enforced; lockfiles, codegen, vendor, and binary files are excluded.",
    "",
    "Offending staged file(s):",
  ];

  for (const violation of violations) {
    const excessTokens = violation.tokens - TOKEN_LIMIT;
    const excessBytes = violation.bytes - MAX_BYTES;

    const displayPath = path.isAbsolute(violation.filePath)
      ? path.relative(repoRoot, violation.filePath).replaceAll("\\", "/")
      : violation.filePath.replaceAll("\\", "/");

    lines.push(
      `  ✖ ${displayPath}`,
      `    Size:    ${violation.bytes.toLocaleString()} bytes (~${violation.tokens.toLocaleString()} tokens)`,
      `    Limit:   ${MAX_BYTES.toLocaleString()} bytes (${TOKEN_LIMIT.toLocaleString()} tokens)`,
      `    Excess:  +${excessBytes.toLocaleString()} bytes (+${excessTokens.toLocaleString()} tokens)`,
      ""
    );
  }

  lines.push(
    "-".repeat(80),
    "WHY THIS RULE EXISTS",
    "-".repeat(80),
    "Files over 5,000 tokens degrade coding agent attention, cause hallucinations,",
    "increase latency, and saturate context windows during pair programming.",
    "Keeping files small, modular, and single-purpose ensures agents can reason",
    "effectively and generate reliable code diffs.",
    "",
    "-".repeat(80),
    "EXPLICIT INSTRUCTIONS ON HOW TO SPLIT FILES",
    "-".repeat(80),
    "",
    "1. For TypeScript / JavaScript Modules (.ts, .tsx, .js):",
    "   a. Extract Type Declarations:",
    "      Move interfaces, type aliases, and enums into a sibling `[name].types.ts`",
    "      or shared `types.ts` file.",
    "   b. Extract Pure Helpers and Utilities:",
    "      Move stateless utility functions, formatters, and mathematical helpers into",
    "      `[name].utils.ts` or `[feature].primitives.ts`.",
    "   c. Separate Domain Logic from I/O (Ports & Adapters):",
    "      Separate pure domain flows and business invariants from data stores,",
    "      database queries, and external APIs (e.g. separate Stores/Adapters from Flows).",
    "   d. Decompose Large UI Components:",
    "      Extract child UI subcomponents into separate files (e.g., `Header.tsx`,",
    "      `Sidebar.tsx`) and encapsulate state management into custom hooks (`use[Name].ts`).",
    "   e. Extract Constants & Configuration:",
    "      Move large static arrays, lookup tables, and default configurations into",
    "      `[name].constants.ts` or `[name].config.ts`.",
    "",
    "2. For Documentation (.md):",
    "   a. Break long monolithic documents into focused sections under a dedicated directory",
    "      (e.g., `docs/[feature]/overview.md`, `docs/[feature]/architecture.md`).",
    "   b. Extract extensive tables, specifications, or glossaries into companion reference docs.",
    "",
    "3. For Test Files (*.test.ts, *.spec.ts):",
    "   a. Split test suites by behavior or sub-feature into separate test files",
    "      (e.g., `auth.test.ts` -> `auth-login.test.ts`, `auth-session.test.ts`).",
    "   b. Move shared test fixtures, mock factories, and sample payloads into `fixtures.ts`.",
    "",
    "-".repeat(80),
    "RESOLUTION WORKFLOW",
    "-".repeat(80),
    "  1. Review the offending file(s) and identify cohesive segments to extract.",
    "  2. Split the file into smaller modules following the instructions above.",
    "  3. Re-export symbols or update imports across the codebase.",
    "  4. Run validation: `vp check` and `vp test`.",
    "  5. Stage the changes: `git add <split-files>`.",
    "  6. Retry your commit: `git commit`.",
    "=".repeat(80),
    ""
  );

  return lines.join("\n");
};
