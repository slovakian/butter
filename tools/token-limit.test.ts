import { describe, expect, it } from "vite-plus/test";

import {
  BYTES_PER_TOKEN,
  calculateTokens,
  checkFiles,
  formatErrorMessage,
  isIgnoredFile,
  MAX_BYTES,
  TOKEN_LIMIT,
} from "./token-limit.ts";

describe("token limit calculations", () => {
  it("defines constants accurately", () => {
    expect(BYTES_PER_TOKEN).toBe(4);
    expect(TOKEN_LIMIT).toBe(5000);
    expect(MAX_BYTES).toBe(20_000);
  });

  it("calculates tokens from byte counts for small sizes", () => {
    expect(calculateTokens(0)).toBe(0);
    expect(calculateTokens(4)).toBe(1);
    expect(calculateTokens(5)).toBe(2);
    expect(calculateTokens(100)).toBe(25);
  });

  it("calculates tokens around the 5,000 token limit", () => {
    expect(calculateTokens(19_999)).toBe(5000);
    expect(calculateTokens(20_000)).toBe(5000);
    expect(calculateTokens(20_001)).toBe(5001);
    expect(calculateTokens(24_000)).toBe(6000);
  });
});

describe("isIgnoredFile - lockfiles", () => {
  it("ignores node package manager lockfiles", () => {
    expect(isIgnoredFile("pnpm-lock.yaml")).toBeTruthy();
    expect(isIgnoredFile("package-lock.json")).toBeTruthy();
    expect(isIgnoredFile("yarn.lock")).toBeTruthy();
    expect(isIgnoredFile("bun.lock")).toBeTruthy();
    expect(isIgnoredFile("bun.lockb")).toBeTruthy();
  });

  it("ignores non-node package manager lockfiles and nested lockfiles", () => {
    expect(isIgnoredFile("skills-lock.json")).toBeTruthy();
    expect(isIgnoredFile("Cargo.lock")).toBeTruthy();
    expect(isIgnoredFile("Gemfile.lock")).toBeTruthy();
    expect(isIgnoredFile("poetry.lock")).toBeTruthy();
    expect(isIgnoredFile("sub/dir/pnpm-lock.yaml")).toBeTruthy();
  });
});

describe("isIgnoredFile - codegen and vendor files", () => {
  it("ignores codegen files by filename pattern", () => {
    expect(isIgnoredFile("apps/website/src/routeTree.gen.ts")).toBeTruthy();
    expect(isIgnoredFile("src/schema.gen.ts")).toBeTruthy();
    expect(isIgnoredFile("src/api.generated.ts")).toBeTruthy();
    expect(isIgnoredFile("src/proto.pb.ts")).toBeTruthy();
    expect(isIgnoredFile("dist/bundle.min.js")).toBeTruthy();
  });

  it("ignores sourcemap files", () => {
    expect(isIgnoredFile("dist/bundle.js.map")).toBeTruthy();
  });

  it("ignores vendor and build directories", () => {
    expect(
      isIgnoredFile(
        "tools/oxlint/anti-slop/vendor/eslint-stylistic/padding-line-between-statements.ts"
      )
    ).toBeTruthy();
    expect(isIgnoredFile(".vite-hooks/_/pre-commit")).toBeTruthy();
    expect(isIgnoredFile("dist/index.js")).toBeTruthy();
    expect(isIgnoredFile(".tanstack/cache.json")).toBeTruthy();
  });

  it("ignores files with codegen header markers", () => {
    expect(
      isIgnoredFile(
        "src/generated-client.ts",
        "// @generated by tool\nexport const x = 1;"
      )
    ).toBeTruthy();
    expect(
      isIgnoredFile(
        "src/routes.ts",
        "/* This file was automatically generated by router */"
      )
    ).toBeTruthy();
    expect(
      isIgnoredFile(
        "src/models.ts",
        "// DO NOT EDIT: changes will be overwritten"
      )
    ).toBeTruthy();
    expect(
      isIgnoredFile(
        "src/upstream.ts",
        "// Vendored from upstream-repo; see LICENSE"
      )
    ).toBeTruthy();
  });
});

describe("isIgnoredFile - binary and media assets", () => {
  it("ignores images and vector assets", () => {
    expect(isIgnoredFile("assets/hero.png")).toBeTruthy();
    expect(isIgnoredFile("assets/icon.svg")).toBeTruthy();
    expect(isIgnoredFile("assets/photo.jpg")).toBeTruthy();
  });

  it("ignores fonts, archives, documents, and binary data", () => {
    expect(isIgnoredFile("fonts/inter.woff2")).toBeTruthy();
    expect(isIgnoredFile("archive.zip")).toBeTruthy();
    expect(isIgnoredFile("document.pdf")).toBeTruthy();
    expect(isIgnoredFile("data.bin", "text before\0null byte")).toBeTruthy();
  });
});

describe("isIgnoredFile - agent-authored files", () => {
  it("does not ignore agent-authored source code and components", () => {
    expect(isIgnoredFile("src/index.ts")).toBeFalsy();
    expect(isIgnoredFile("src/components/Button.tsx")).toBeFalsy();
  });

  it("does not ignore agent-authored configs and docs", () => {
    expect(isIgnoredFile("docs/architecture.md")).toBeFalsy();
    expect(isIgnoredFile("package.json")).toBeFalsy();
    expect(isIgnoredFile("vite.config.ts")).toBeFalsy();
    expect(isIgnoredFile("tsconfig.json")).toBeFalsy();
  });
});

describe(checkFiles, () => {
  it("passes files that are under the 5,000 token limit", () => {
    const result = checkFiles(["package.json", "tsconfig.json"]);
    expect(result.violations).toHaveLength(0);
    expect(result.checkedFiles).toContain("package.json");
  });

  it("ignores lockfiles even if large", () => {
    const result = checkFiles(["pnpm-lock.yaml"]);
    expect(result.violations).toHaveLength(0);
    expect(result.ignoredFiles).toContain("pnpm-lock.yaml");
  });
});

describe(formatErrorMessage, () => {
  it("includes header and file details", () => {
    const violations = [
      {
        bytes: 24_800,
        filePath: "apps/website/src/huge-module.ts",
        tokens: 6200,
      },
    ];

    const message = formatErrorMessage(violations);

    expect(message).toContain("COMMIT REJECTED");
    expect(message).toContain("apps/website/src/huge-module.ts");
    expect(message).toContain("5,000 tokens");
    expect(message).toContain("20,000 bytes");
    expect(message).toContain("6,200 tokens");
  });

  it("includes code splitting instructions", () => {
    const violations = [
      {
        bytes: 24_800,
        filePath: "apps/website/src/huge-module.ts",
        tokens: 6200,
      },
    ];

    const message = formatErrorMessage(violations);

    expect(message).toContain("EXPLICIT INSTRUCTIONS ON HOW TO SPLIT FILES");
    expect(message).toContain("Extract Type Declarations");
    expect(message).toContain("Extract Pure Helpers and Utilities");
    expect(message).toContain("Separate Domain Logic from I/O");
    expect(message).toContain("Decompose Large UI Components");
  });

  it("includes documentation and test splitting instructions", () => {
    const violations = [
      {
        bytes: 24_800,
        filePath: "docs/huge-guide.md",
        tokens: 6200,
      },
    ];

    const message = formatErrorMessage(violations);

    expect(message).toContain("Extract Constants & Configuration");
    expect(message).toContain("For Documentation (.md)");
    expect(message).toContain("For Test Files (*.test.ts, *.spec.ts)");
    expect(message).toContain("RESOLUTION WORKFLOW");
  });
});
